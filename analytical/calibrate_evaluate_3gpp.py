import json
import time
import os
import threading
from pathlib import Path

import numpy as np
import pandas as pd
import psutil

DATA = Path("data/processed/powder_benchmark_with_los.csv")
CONFIG = Path("configs/analytical_3gpp.json")

OUT = Path("results/analytical/final")
OUT.mkdir(parents=True, exist_ok=True)

resources_rows = []
stop_event = threading.Event()


def monitor(interval=0.02):
    p = psutil.Process(os.getpid())
    t0 = time.perf_counter()
    p.cpu_percent(None)

    while not stop_event.is_set():
        resources_rows.append({
            "elapsed_s": time.perf_counter() - t0,
            "cpu_percent": p.cpu_percent(None),
            "ram_mb": p.memory_info().rss / 1024**2,
            "system_ram_percent": psutil.virtual_memory().percent
        })
        time.sleep(interval)


def umi_los_pathloss(d2d, fc_ghz, h_bs=10.0, h_ut=1.5):
    d2d = np.asarray(d2d, dtype=float)
    d2d = np.maximum(d2d, 10.0)

    d3d = np.sqrt(
        d2d**2 +
        (h_bs - h_ut)**2
    )

    # TR 38.901 UMi effective heights
    h_e = 1.0
    h_bs_eff = h_bs - h_e
    h_ut_eff = h_ut - h_e

    c = 3e8
    fc_hz = fc_ghz * 1e9

    d_bp = (
        4.0 *
        h_bs_eff *
        h_ut_eff *
        fc_hz / c
    )

    pl1 = (
        32.4
        + 21.0*np.log10(d3d)
        + 20.0*np.log10(fc_ghz)
    )

    pl2 = (
        32.4
        + 40.0*np.log10(d3d)
        + 20.0*np.log10(fc_ghz)
        - 9.5*np.log10(
            d_bp**2 +
            (h_bs-h_ut)**2
        )
    )

    return np.where(
        d2d <= d_bp,
        pl1,
        pl2
    )


with open(CONFIG) as f:
    cfg = json.load(f)

df = pd.read_csv(DATA)

# Verify LOS result
if "los_class_2d" not in df.columns:
    raise RuntimeError("LOS classification missing.")

if not (df["los_class_2d"] == "LOS").all():
    raise RuntimeError(
        "Dataset contains NLOS points. "
        "This script is currently configured for the verified all-LOS case."
    )

train = df[df["run"] == "run1"].copy()
test  = df[df["run"] == "run2"].copy()

fc = cfg["frequency_ghz"]
h_bs = cfg["h_bs_m"]
h_ut = cfg["h_ut_m"]

# Use geometric distance already generated by OSM LOS script
train["pathloss_db"] = umi_los_pathloss(
    train["ray_distance_2d_m"].to_numpy(),
    fc,
    h_bs,
    h_ut
)

test["pathloss_db"] = umi_los_pathloss(
    test["ray_distance_2d_m"].to_numpy(),
    fc,
    h_bs,
    h_ut
)

# ============================================================
# CALIBRATION USING RUN1 ONLY
# ============================================================

effective_power_samples = (
    train["rsrp_real_dbm"].to_numpy()
    +
    train["pathloss_db"].to_numpy()
)

p_ref_star = float(
    np.median(effective_power_samples)
)

train["rsrp_3gpp_dbm"] = (
    p_ref_star -
    train["pathloss_db"]
)

train["abs_error_db"] = np.abs(
    train["rsrp_real_dbm"] -
    train["rsrp_3gpp_dbm"]
)

train_mae = float(
    train["abs_error_db"].mean()
)

# ============================================================
# FINAL TEST: RUN2 ONLY
# ============================================================

# Warm-up
_ = umi_los_pathloss(
    test["ray_distance_2d_m"].to_numpy()[:10],
    fc,
    h_bs,
    h_ut
)

thread = threading.Thread(
    target=monitor,
    daemon=True
)
thread.start()

start = time.perf_counter()

pl_test = umi_los_pathloss(
    test["ray_distance_2d_m"].to_numpy(),
    fc,
    h_bs,
    h_ut
)

pred_test = p_ref_star - pl_test

runtime_s = time.perf_counter() - start

test["pathloss_db"] = pl_test
test["rsrp_3gpp_dbm"] = pred_test

test["abs_error_db"] = np.abs(
    test["rsrp_real_dbm"] -
    test["rsrp_3gpp_dbm"]
)

test["signed_error_db"] = (
    test["rsrp_3gpp_dbm"] -
    test["rsrp_real_dbm"]
)

test_mae = float(
    test["abs_error_db"].mean()
)

# Repeat workload only for resource-profile time series
profile_start = time.perf_counter()
profile_iterations = 0

while time.perf_counter() - profile_start < 2.0:
    pl = umi_los_pathloss(
        test["ray_distance_2d_m"].to_numpy(),
        fc,
        h_bs,
        h_ut
    )
    _ = p_ref_star - pl
    profile_iterations += 1

stop_event.set()
thread.join()

resources = pd.DataFrame(resources_rows)

# ============================================================
# SAVE RAW RESULTS
# ============================================================

train["split"] = "calibration"
test["split"] = "test"

predictions = pd.concat(
    [train, test],
    ignore_index=True
)

pred_cols = [
    "sample_id",
    "run",
    "split",
    "timestamp",
    "latitude",
    "longitude",
    "height_m",
    "gps_interpolated",
    "los_class_2d",
    "ray_distance_2d_m",
    "rsrp_real_dbm",
    "pathloss_db",
    "rsrp_3gpp_dbm",
    "abs_error_db"
]

predictions[pred_cols].to_csv(
    OUT / "predictions.csv",
    index=False
)

resources.to_csv(
    OUT / "resources.csv",
    index=False
)

calibration = {
    "calibration_run": "run1",
    "n_calibration_samples": int(len(train)),
    "parameter": "effective_reference_power_dbm",
    "estimator": "median(rsrp_real_dbm + pathloss_db)",
    "effective_reference_power_dbm": p_ref_star,
    "important_note": (
        "This is an effective fitted reference-power term. "
        "It is not claimed to be the physical RU transmit power or EIRP."
    )
}

with open(
    OUT / "calibration.json",
    "w"
) as f:
    json.dump(calibration, f, indent=2)

metrics = {
    "model": "3GPP_TR_38.901_UMi_LOS_calibrated",
    "frequency_ghz": fc,
    "h_bs_m": h_bs,
    "h_ut_m": h_ut,

    "los_classification": "OSM footprint geometry",
    "n_total_samples": int(len(df)),

    "n_calibration_samples": int(len(train)),
    "n_test_samples": int(len(test)),

    "effective_reference_power_dbm": p_ref_star,

    "calibration_mae_db": train_mae,
    "test_mae_db": test_mae,

    "test_runtime_s": float(runtime_s),
    "test_time_per_sample_us": float(
        runtime_s / len(test) * 1e6
    ),

    "profile_duration_s": 2.0,
    "profile_iterations": int(profile_iterations),

    "cpu_mean_percent": (
        float(resources["cpu_percent"].mean())
        if len(resources)
        else None
    ),

    "cpu_peak_percent": (
        float(resources["cpu_percent"].max())
        if len(resources)
        else None
    ),

    "ram_mean_mb": (
        float(resources["ram_mb"].mean())
        if len(resources)
        else None
    ),

    "ram_peak_mb": (
        float(resources["ram_mb"].max())
        if len(resources)
        else None
    )
}

with open(
    OUT / "metrics.json",
    "w"
) as f:
    json.dump(metrics, f, indent=2)

print("="*72)
print("FINAL 3GPP ANALYTICAL BASELINE")
print("="*72)

print("Propagation state : LOS for all samples")
print("Calibration       : Run1")
print("Evaluation        : Run2")

print()
print("Calibration samples:", len(train))
print("Test samples       :", len(test))

print()
print(
    f"Effective calibrated reference power: "
    f"{p_ref_star:.3f} dBm"
)

print()
print(
    f"Run1 calibration MAE: "
    f"{train_mae:.3f} dB"
)

print(
    f"Run2 FINAL TEST MAE: "
    f"{test_mae:.3f} dB"
)

print()
print(
    f"Run2 inference runtime: "
    f"{runtime_s*1000:.6f} ms"
)

print(
    f"Run2 time/sample: "
    f"{runtime_s/len(test)*1e6:.6f} us"
)

print()
print(
    f"CPU mean/peak: "
    f"{metrics['cpu_mean_percent']:.2f}% / "
    f"{metrics['cpu_peak_percent']:.2f}%"
)

print(
    f"RAM mean/peak: "
    f"{metrics['ram_mean_mb']:.2f} / "
    f"{metrics['ram_peak_mb']:.2f} MB"
)

print()
print("Saved:")
print(OUT / "predictions.csv")
print(OUT / "resources.csv")
print(OUT / "calibration.json")
print(OUT / "metrics.json")
